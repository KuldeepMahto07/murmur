/**
 * Vendor-side licence tool. The private key never enters the repository; it lives in
 * %USERPROFILE%\.fetchline-vendor\ (override with FETCHLINE_VENDOR_DIR). Back that folder up:
 * losing it means you can no longer issue keys that existing builds accept.
 *
 *   node scripts/license-tool.ts keygen                      create the keypair (once); writes engine/license-key.ts
 *   node scripts/license-tool.ts issue --email a@b.c --plan lifetime|yearly [--seats 3] [--expires YYYY-MM-DD]
 *   node scripts/license-tool.ts verify FL1-...
 */
import crypto from 'node:crypto';
import fs from 'node:fs/promises';
import { existsSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { parseArgs } from 'node:util';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { checkKey, signKey, type LicensePayload } from '../engine/license.ts';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const VENDOR = process.env.FETCHLINE_VENDOR_DIR ?? path.join(os.homedir(), '.fetchline-vendor');
const PRIVATE = path.join(VENDOR, 'license-private.pem');
const LEDGER = path.join(VENDOR, 'issued.csv');
const PUBLIC_TS = path.join(ROOT, 'engine', 'license-key.ts');

const { positionals, values } = parseArgs({
  allowPositionals: true,
  options: {
    email: { type: 'string' },
    plan: { type: 'string' },
    seats: { type: 'string', default: '3' },
    expires: { type: 'string' },
    force: { type: 'boolean', default: false },
  },
});
const [cmd, arg] = positionals;

async function publicB64FromPrivate(pem: string) {
  return crypto.createPublicKey(crypto.createPrivateKey(pem)).export({ format: 'der', type: 'spki' }).toString('base64');
}

async function writePublicTs(b64: string) {
  await fs.writeFile(
    PUBLIC_TS,
    `// Public half of the Harbor licence signing key (generated by scripts/license-tool.ts keygen).\n` +
      `// Safe to commit. The private half stays in the vendor folder, never in this repository.\n` +
      `export const LICENSE_PUBLIC_KEY = '${b64}';\n`,
  );
}

switch (cmd) {
  case 'keygen': {
    if (existsSync(PRIVATE) && !values.force) {
      // Keep the existing key: re-sync the engine's public key from it instead.
      const b64 = await publicB64FromPrivate(await fs.readFile(PRIVATE, 'utf8'));
      await writePublicTs(b64);
      console.log(`A signing key already exists at ${PRIVATE}; engine/license-key.ts re-synced. (--force replaces it and invalidates every issued key.)`);
      break;
    }
    const { privateKey } = crypto.generateKeyPairSync('ed25519');
    const pem = privateKey.export({ format: 'pem', type: 'pkcs8' }).toString();
    await fs.mkdir(VENDOR, { recursive: true });
    await fs.writeFile(PRIVATE, pem, { mode: 0o600 });
    if (process.platform === 'win32') {
      // mode bits mean little on Windows: limit the file to the current user with an ACL.
      execFileSync('icacls', [PRIVATE, '/inheritance:r', '/grant:r', `${process.env.USERNAME}:F`], { stdio: 'ignore' });
    }
    await writePublicTs(await publicB64FromPrivate(pem));
    console.log(`Private key: ${PRIVATE}  (back this up; never commit it)`);
    console.log(`Public key written to ${path.relative(process.cwd(), PUBLIC_TS)}`);
    break;
  }
  case 'issue': {
    const plan = values.plan === 'yearly' ? 'pro-yearly' : values.plan === 'lifetime' ? 'pro-lifetime' : null;
    if (!values.email || !plan) throw new Error('usage: issue --email <email> --plan lifetime|yearly [--seats N] [--expires YYYY-MM-DD]');
    // Local calendar dates (the vendor's day), not UTC.
    const day = (d: Date) => `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;
    const issued = day(new Date());
    const yearOut = day(new Date(Date.now() + 365 * 86_400_000));
    const payload: LicensePayload = {
      v: 1,
      id: crypto.randomBytes(6).toString('hex'),
      email: values.email,
      plan,
      seats: Number(values.seats) || 3,
      issued,
      expires: values.expires ?? (plan === 'pro-yearly' ? yearOut : null),
    };
    const key = signKey(payload, await fs.readFile(PRIVATE, 'utf8'));
    if (!existsSync(LEDGER)) await fs.writeFile(LEDGER, 'id,email,plan,seats,issued,expires\n');
    await fs.appendFile(LEDGER, [payload.id, payload.email, payload.plan, payload.seats, payload.issued, payload.expires ?? ''].join(',') + '\n');
    console.log(key);
    break;
  }
  case 'verify': {
    const r = checkKey(arg ?? '');
    console.log(r.ok ? JSON.stringify(r.payload, null, 2) : `INVALID: ${r.error}`);
    process.exitCode = r.ok ? 0 : 1;
    break;
  }
  default:
    console.log('commands: keygen | issue --email <e> --plan lifetime|yearly | verify <key>');
}
